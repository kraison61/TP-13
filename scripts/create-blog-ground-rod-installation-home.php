<p>สายดินไม่จำเป็นต้องใหญ่กว่าสายไฟของวงจรนั้น ที่มา: คู่มือการติดตั้งระบบไฟฟ้าอย่างมืออาชีพ ฉบับปรับปรุงตามมาตรฐานฯ 2564 (ลือชัย ทองนิล, ไทย-ยาซากิ) หัวข้อ 4.4 ตาราง 4.1–4.2 และตาราง 5.5</p>

<p>บ้านเก่าที่เดินสายไฟแค่ 2 สาย ตอกแท่งอย่างเดียวไม่พอ ต้อง<a href="/electrical-wiring">เดินสายดินเส้นที่ 3</a> ไปถึงปลั๊กและเครื่องใช้ไฟฟ้าด้วย ไม่อย่างนั้นเครื่องใช้ไฟฟ้าก็ยังไม่มีทางให้ไฟรั่วลงดิน</p>

<h2>วิธีการตอกกราวด์แบบเดลต้าคืออะไร ต้องใช้เมื่อไหร่?</h2>
<p>การตอกกราวด์แบบเดลต้า คือการตอกแท่งกราวด์ 3 แท่งเป็นรูปสามเหลี่ยม วางห่างกันอย่างน้อยเท่ากับความยาวแท่ง (2.4–3 เมตร) แล้วเชื่อมทุกแท่งด้วยสายทองแดงเปลือยฝังดิน ทำให้ค่าความต้านทานรวมลดเหลือประมาณ 42% ของแท่งเดี่ยว ใช้เมื่อตอกแท่งเดียวแล้ววัดได้เกิน 5 โอห์ม</p>

<p>มาตรฐาน วสท. 2564 ไม่ได้บังคับให้วางเป็นสามเหลี่ยม เพียงกำหนดว่าถ้าวัดแล้วค่าเกิน ให้ปักหลักดินเพิ่มและต่อหลักดินทั้งหมดเข้าด้วยกัน การวางเดลต้าเป็นวิธีหนึ่งเมื่อพื้นที่พอ มักเจอในบ้านบนดินถมใหม่ ดินทราย หรือดินแห้ง — รวมถึงงานที่ต้องมีกราวด์ดีก่อนติดตั้ง<a href="/cctv-installation">กล้องวงจรปิด</a> หรือ<a href="/outdoor-lan-cabling">เดินสาย LAN</a> นอกอาคาร</p>

